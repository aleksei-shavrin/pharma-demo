#!/usr/bin/env node
/**
 * Ensure gitignored DX auth files exist. Never overwrites existing credentials.
 * Never prints password/hash/secret values — only paths and key names.
 *
 *   .env.dev-auth              — COOKIE_SECURE, LOGIN_USERNAME, SESSION_SECRET, PUBLIC_ORIGIN
 *   .dev-login-password        — plaintext password (chmod 600)
 *   .dev-login-password-hash   — raw bcrypt; mounted into api (not compose env_file)
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const AUTH_ENV = path.join(ROOT, '.env.dev-auth');
const PASS_FILE = path.join(ROOT, '.dev-login-password');
const HASH_FILE = path.join(ROOT, '.dev-login-password-hash');

const REQUIRED_ENV = [
  'COOKIE_SECURE',
  'LOGIN_USERNAME',
  'SESSION_SECRET',
  'PUBLIC_ORIGIN',
];

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\n/)) {
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i < 0) continue;
    out[line.slice(0, i)] = line.slice(i + 1);
  }
  return out;
}

function hasAllKeys(env) {
  return REQUIRED_ENV.every((k) => env[k] != null && String(env[k]).length > 0);
}

function caddyHash(plaintext) {
  const r = spawnSync(
    'docker',
    ['run', '--rm', 'caddy:2-alpine', 'caddy', 'hash-password', '--plaintext', plaintext],
    { encoding: 'utf8' },
  );
  if (r.status !== 0) {
    throw new Error(
      `caddy hash-password failed: ${(r.stderr || r.stdout || '').slice(0, 200)}`,
    );
  }
  return r.stdout.trim();
}

const existing = parseEnvFile(AUTH_ENV);
const complete =
  hasAllKeys(existing) &&
  fs.existsSync(PASS_FILE) &&
  fs.existsSync(HASH_FILE) &&
  fs.statSync(HASH_FILE).size > 20;

if (complete) {
  console.log(`ensure-dev-auth-env: keep existing ${path.relative(ROOT, AUTH_ENV)}`);
  console.log(`ensure-dev-auth-env: password ${path.relative(ROOT, PASS_FILE)}`);
  console.log(`ensure-dev-auth-env: hash file ${path.relative(ROOT, HASH_FILE)}`);
  console.log(`ensure-dev-auth-env: keys ${REQUIRED_ENV.join(',')}`);
  process.exit(0);
}

if (hasAllKeys(existing) && (!fs.existsSync(PASS_FILE) || !fs.existsSync(HASH_FILE))) {
  console.error(
    'ensure-dev-auth-env: auth env exists but password/hash file missing — delete .env.dev-auth to re-bootstrap',
  );
  process.exit(1);
}

// Local DX demo credentials (gitignored files). Not a runtime backdoor —
// Nest still verifies bcrypt via LOGIN_PASSWORD_HASH_FILE.
const username = 'admin';
const plaintext = 'admin';
const sessionSecret = crypto.randomBytes(32).toString('hex');
const hashRaw = caddyHash(plaintext);
if (!hashRaw.includes('$') || hashRaw.length < 40) {
  throw new Error('caddy hash-password returned unexpected output');
}

const body = [
  '# Generated by tools/dev/ensure-dev-auth-env.mjs — gitignored. Do not commit.',
  '# bcrypt hash is NOT here (Compose interpolates $). See .dev-login-password-hash.',
  '# Plaintext for humans: .dev-login-password (chmod 600).',
  'COOKIE_SECURE=false',
  `LOGIN_USERNAME=${username}`,
  ['SESSION_SECRET', sessionSecret].join('='),
  'PUBLIC_ORIGIN=http://localhost:3080',
  'WEB_ORIGIN=http://localhost:3080',
  '',
].join('\n');

fs.writeFileSync(AUTH_ENV, body, { mode: 0o600 });
fs.chmodSync(AUTH_ENV, 0o600);
fs.writeFileSync(PASS_FILE, `${plaintext}\n`, { mode: 0o600 });
fs.chmodSync(PASS_FILE, 0o600);
fs.writeFileSync(HASH_FILE, `${hashRaw}\n`, { mode: 0o600 });
fs.chmodSync(HASH_FILE, 0o600);

console.log(`ensure-dev-auth-env: wrote ${path.relative(ROOT, AUTH_ENV)}`);
console.log(`ensure-dev-auth-env: wrote ${path.relative(ROOT, PASS_FILE)}`);
console.log(`ensure-dev-auth-env: wrote ${path.relative(ROOT, HASH_FILE)}`);
console.log(`ensure-dev-auth-env: LOGIN_USERNAME=${username}`);
console.log(`ensure-dev-auth-env: keys ${REQUIRED_ENV.join(',')}`);
